//! Turns class tables into LuaLS text.

use std::fmt::Write;

use super::classes::{Class, Field, Kind, Ty};

/// The LuaLS type of `ty`.
fn lua_type(ty: &Ty) -> String {
    match ty {
        Ty::Int => "integer".into(),
        Ty::Bool => "boolean".into(),
        Ty::Str => "string".into(),
        Ty::Ref(kind) => format!("string # id of a `{kind}`"),
        Ty::Enum(names) => names
            .iter()
            .map(|name| format!("\"{name}\""))
            .collect::<Vec<_>>()
            .join("|"),
        Ty::List(item) => format!("({})[]", bare(item)),
        Ty::Map(key, value) => format!("table<{}, {}>", bare(key), bare(value)),
        Ty::Class(name) => format!("strata.{name}"),
        Ty::Func => "fun(...): any".into(),
        Ty::Any => "any".into(),
    }
}

/// Like [`lua_type`], without the trailing comment that `Ty::Ref` adds.
fn bare(ty: &Ty) -> String {
    match ty {
        Ty::Ref(_) => "string".into(),
        _ => lua_type(ty),
    }
}

fn class(out: &mut String, name: &str, fields: &[Field], extra: &[Field]) {
    writeln!(out, "---@class strata.{name}").unwrap();
    for field in fields.iter().chain(extra) {
        let mark = if field.required { "" } else { "?" };
        writeln!(
            out,
            "---@field {}{} {}",
            field.name,
            mark,
            lua_type(&field.ty)
        )
        .unwrap();
    }
    out.push('\n');
}

/// The full stub file of one constructor.
pub(super) fn file(kind: &Kind) -> String {
    let mut out = String::from("---@meta\n-- Generated by `strata stubs`. Do not edit.\n\n");
    let own = Class {
        name: kind.class,
        fields: kind.fields,
    };
    let tail: &[Field] = if kind.common {
        &super::classes::COMMON
    } else {
        &[]
    };
    for nested in kind.nested {
        class(&mut out, nested.name, nested.fields, &[]);
    }
    class(&mut out, own.name, own.fields, tail);
    writeln!(out, "---@param def strata.{}", own.name).unwrap();
    writeln!(out, "---@return strata.{}", own.name).unwrap();
    writeln!(out, "function {}(def) end", kind.name).unwrap();
    out
}
